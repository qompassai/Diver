#!/usr/bin/env lua5.1, JIT
--- Neovim API type extensions — type-checker dictionary (never runs).
---
--- Plain-language version: this file never runs -- Neovim never loads it at startup. It is a dictionary of shapes
--- (type annotations) for the lua-language-server type checker, so the editor can offer completions and catch
--- mistakes while you edit. Think of it as the answer key the teacher uses, not a lesson.
---
--- Design principle (2026-10-05 audit): Neovim 0.13 ships comprehensive native LuaCATS annotations in
--- `$VIMRUNTIME/lua/vim/_meta/` (api.gen.lua: 185 vim.api functions, vimfn.gen.lua: 453 vim.fn functions,
--- options.gen.lua: every option, plus vim.lsp.Config, vim.pack.Spec, etc.). This file therefore contains ONLY:
---   1. Types Neovim does not define natively (vim.opt family, gh.Opts, CoxpcallModule).
---   2. Extensions where native types are weak (vim.g/vim.b field lists — native casts them with no fields).
---   3. Aliases in our own namespace that do not conflict with native.
--- It deliberately does NOT redefine vim.api, vim.fn, vim.o, vim.bo, vim.wo, vim.uv, vim.treesitter,
--- vim.diagnostic, vim.fs functions, or vim.pack.Spec — those are native, complete, and generated from source.
--- Redefining them would silently union (not override) field types, creating confusing A|B hovers.
