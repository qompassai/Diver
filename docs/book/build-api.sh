#!/usr/bin/env bash
# build-api.sh -- generate the Diver API reference into the mdBook.
#
# Purpose: turn the config's LuaCATS annotations into browsable
#   markdown with emmylua_doc_cli (LuaCATS-native) and rebuild the
#   mdBook under docs/book/. The generated pages are build output:
#   they live in docs/book/src/api/ (gitignored) and are regenerated
#   on demand; the annotations in the Lua sources are the truth.
#
# Usage: build-api.sh [REPO_ROOT]
#   REPO_ROOT defaults to the repo this script lives in (docs/book/
#   ../..). The root must contain lua/ and .luarc.json.
#
# Side effects: rewrites docs/book/src/api/, splices the generated
#   section of docs/book/src/SUMMARY.md between the API markers,
#   writes docs/book/.last-build, rebuilds docs/book/book/.
# Exit codes: 0 success, 1 failure, 2 usage error.
# Required tools: emmylua_doc_cli (PATH or ~/.cargo/bin), mdbook,
#   python3, timeout; nvim optional (VIMRUNTIME derivation).

if ((BASH_VERSINFO[0] < 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] < 4))); then
    printf 'build-api: bash >= 4.4 required\n' >&2
    exit 2
fi

set -euo pipefail

readonly SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
readonly DEFAULT_ROOT="$(cd -- "$SCRIPT_DIR/../.." && pwd -P)"
readonly GEN_TIMEOUT_SEC=900
readonly SUMMARY_BEGIN='<!-- API:BEGIN (generated by build-api.sh; do not edit between the markers) -->'
readonly SUMMARY_END='<!-- API:END -->'

die() {
    printf 'build-api: %s\n' "$*" >&2
    exit 1
}

log() {
    printf 'build-api: %s\n' "$*" >&2
}

main() {
    if (($# > 1)); then
        printf 'usage: build-api.sh [REPO_ROOT]\n' >&2
        exit 2
    fi
    local root="${1:-$DEFAULT_ROOT}"
    [[ -d "$root/lua" ]] || die "not a diver repo root (no lua/ dir): $root"
    [[ -f "$root/.luarc.json" ]] || die "missing .luarc.json in $root"
    local book_dir="$root/docs/book"
    local src_dir="$book_dir/src"
    local api_dir="$src_dir/api"
    [[ -f "$src_dir/SUMMARY.md" ]] || die "book project not installed (missing $src_dir/SUMMARY.md)"
    case "$api_dir" in
        "$book_dir"/src/api) ;;
        *) die "internal: unexpected api dir: $api_dir" ;;
    esac

    local emmy=''
    if command -v emmylua_doc_cli >/dev/null 2>&1; then
        emmy="$(command -v emmylua_doc_cli)"
    elif [[ -x "$HOME/.cargo/bin/emmylua_doc_cli" ]]; then
        emmy="$HOME/.cargo/bin/emmylua_doc_cli"
    else
        die 'emmylua_doc_cli not found (PATH or ~/.cargo/bin)'
    fi
    command -v mdbook >/dev/null 2>&1 || die 'mdbook not found on PATH'
    command -v python3 >/dev/null 2>&1 || die 'python3 not found on PATH'

    local vimruntime="${VIMRUNTIME:-}"
    if [[ -z "$vimruntime" ]]; then
        if command -v nvim >/dev/null 2>&1; then
            vimruntime="$(nvim --headless -u NONE '+echo $VIMRUNTIME' +qa 2>&1 | tail -n 1)"
        fi
        [[ -d "$vimruntime" ]] || vimruntime='/usr/share/nvim/runtime'
    fi

    local stage=''
    stage="$(mktemp -d)"
    trap 'rm -rf -- "$stage"' EXIT

    log "generating API markdown from $root"
    VIMRUNTIME="$vimruntime" timeout "$GEN_TIMEOUT_SEC" "$emmy" \
        -c "$root/.luarc.json" -f markdown -o "$stage/out" "$root" >/dev/null ||
        die 'emmylua_doc_cli failed'
    [[ -d "$stage/out/docs/modules" ]] || die 'generator produced no modules/ directory'

    rm -rf -- "$api_dir"
    mkdir -p "$api_dir/modules" "$api_dir/types"
    cp -a "$stage/out/docs/modules/." "$api_dir/modules/"
    if [[ -d "$stage/out/docs/types" ]]; then
        cp -a "$stage/out/docs/types/." "$api_dir/types/"
    fi

    # Post-pass (whitespace), coverage audit, SUMMARY splice, api/index.
    python3 - "$api_dir" "$src_dir/SUMMARY.md" "$SUMMARY_BEGIN" "$SUMMARY_END" <<'PYEOF'
import pathlib
import sys

api_dir = pathlib.Path(sys.argv[1])
summary_path = pathlib.Path(sys.argv[2])
begin, end = sys.argv[3], sys.argv[4]


def collapse(text):
    out, blank = [], 0
    for line in text.splitlines():
        if line.strip() == '':
            blank += 1
            if blank > 1:
                continue
        else:
            blank = 0
        out.append(line)
    while out and out[0].strip() == '':
        out.pop(0)
    while out and out[-1].strip() == '':
        out.pop()
    return '\n'.join(out) + '\n'


modules = sorted((api_dir / 'modules').glob('*.md'))
types = sorted((api_dir / 'types').glob('*.md'))
entries_total, zero = 0, []
for page in modules + types:
    text = collapse(page.read_text())
    page.write_text(text)
    count = sum(1 for ln in text.splitlines() if ln.startswith('### '))
    entries_total += count
    if page.parent.name == 'modules' and count == 0:
        zero.append(page.stem)

(api_dir / 'index.md').write_text(
    '# API Reference\n\n'
    'Generated from the config\'s LuaCATS annotations by '
    '`docs/book/build-api.sh` (emmylua_doc_cli). Do not edit these '
    'pages; edit the annotations in the Lua sources.\n\n'
    f'- Modules documented: {len(modules)}\n'
    f'- Types documented: {len(types)}\n'
    f'- Documented entries: {entries_total}\n'
)

lines = summary_path.read_text().splitlines()
try:
    i = next(n for n, ln in enumerate(lines) if ln.strip() == begin)
    j = next(n for n, ln in enumerate(lines) if ln.strip() == end)
except StopIteration:
    print('build-api: SUMMARY.md is missing the API markers', file=sys.stderr)
    sys.exit(1)
block = [begin, '', '# API Reference (generated)', '',
         '- [Overview](api/index.md)', '', '## Modules', '']
block += [f'- [{p.stem}](api/modules/{p.name})' for p in modules]
block += ['', '## Types', '']
block += [f'- [{p.stem}](api/types/{p.name})' for p in types]
block += ['', end]
summary_path.write_text('\n'.join(lines[:i] + block + lines[j + 1:]) + '\n')

print(f'build-api: {len(modules)} modules, {len(types)} types, '
      f'{entries_total} documented entries', file=sys.stderr)
if zero:
    print('build-api: modules with zero documented entries (annotation audit):',
          file=sys.stderr)
    for name in zero:
        print(f'build-api:   {name}', file=sys.stderr)
PYEOF

    date +%s >"$book_dir/.last-build"
    (cd "$root" && mdbook build docs/book >/dev/null) || die 'mdbook build failed'
    printf '%s\n' "$book_dir/book/index.html"
}

main "$@"
